def changes():
    rows = read_csv(EV / "CM" / "EVID-030_change-sample-2026H1.csv")
    exc = [r for r in rows if r["assessor_result"].startswith("Exception")]
    res = {
        "population": 212, "sample": len(rows), "sample_seed": 20260618,
        "exceptions": len(exc), "exception_ids": [r["change_id"] for r in exc],
        "emergency_in_sample": sum(r["type"] == "Emergency" for r in rows),
        "emergency_exceptions": sum(r["type"] == "Emergency" for r in exc),
    }
    body = f"""
**Control:** CM-3 Configuration Change Control · **Requirement:** REQ-023 (SOC 2 CC8.1 commitment)
**Evidence:** EVID-030 (production change tickets) · **Method:** Test (random sample of {res['sample']} of {res['population']} production changes, `random.Random({res['sample_seed']})`)

**Criteria:** normal changes are approved *before* deployment. Emergency changes are retro-approved within 2 business days (CMP-006 §4.3). Every change has peer review and test evidence.

| Measure | Result |
|---|---|
| Sample | {res['sample']} of {res['population']} |
| **Exceptions** | **{res['exceptions']}** ({', '.join(res['exception_ids'])}) |
| Emergency changes in sample | {res['emergency_in_sample']} ({res['emergency_exceptions']} with exceptions) |

{md_table(exc, ['change_id', 'type', 'title', 'approved_at', 'deployed_at', 'assessor_result'])}

## Conclusion
**Other Than Satisfied.** 2 of 3 emergency changes in the sample failed the retro-approval standard. One of them (CHG-2026-0412) opened RDP to the internet and was never reverted (**FIND-012**). The pipeline enforces peer review for code, but the **console/manual change path has no preventive gate**. → **FIND-018** / RISK-014 / POAM-018.
"""
    return _write("cm3-change-sample", "Test Result: Change Approval Sample (CM-3)", body, res)


TESTS = {"termination": termination, "termination-validation": termination_validation,
         "logreview": logreview, "vulnsla": vulnsla, "changes": changes}


def run_all():
    results = {k: f() for k, f in TESTS.items()}
    write_json(OUT / "all-results.json", results)
    return results


if __name__ == "__main__":
    arg = sys.argv[1] if len(sys.argv) > 1 else "all"
